/** New descriptions change discovery and the release digest, while schemas,
 * actions, source mappings, fact fingerprints and old releases stay intact. */
export function extendBusinessDescriptions(original: OntologyDocument): OntologyDocument {
  const document = structuredClone(original);
  document.version = '28';
  for (const [id, businessDescription] of Object.entries(businessDescriptions)) {
    const type = document.objects.find(type => type.id === id);
    if (!type) throw new Error(`Business description has no object type: ${id}`);
    type.businessDescription = businessDescription;
  }
  return document;
}

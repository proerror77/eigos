export function extendPaClassificationKernel(original: OntologyDocument): OntologyDocument {
  if (original.version !== '28' || original.objects.length !== Object.keys(paClassifications).length || original.objects.some(type => type.classification || !paClassifications[type.id]))
    throw new DomainError('CONFLICT', 'PA classification requires the complete reviewed v28 predecessor');
  const document = structuredClone(original); document.version = '30';
  for (const type of document.objects) type.classification = structuredClone(paClassifications[type.id]!);
  return document;
}

/** Reuse a field policy only after reconstructing its exact unchanged v28
 * contract. Purpose labels cannot conceal a changed field, action or relation. */
const policyRefs = new WeakMap<OntologyModel, OntologyModel['ref']>();
export function paFieldPolicyRef(model: OntologyModel) {
  const cached = policyRefs.get(model); if (cached) return cached;
  const definition = model.definitionSnapshot();
  if (!definition.objects.some(type => type.classification)) return model.ref;
  const objects = definition.objects.map(type => {
    const { classification: _presentation, ...description } = model.describeType(type.id) as Record<string, unknown>;
    return description;
  });
  const documented = definition.objects.filter(type => type.businessDescription !== undefined);
  const predecessor = { id: model.ref.id, version: '28', digest: digest({ objects,
    interfaces: definition.interfaces.map(type => model.describeType(type.id)), links: definition.links, actions: definition.actions, functions: definition.functions,
    ...(documented.length ? { documentedContracts: documented.map(type => ({ id: type.id, fingerprint: model.fingerprint(type.id) })) } : {}) }) };
  const ref = predecessor.id === 'eigos.business' && predecessor.digest === '04606f93dc6cfd9045ac6b9a0c3dcfa4c8f330689ecbdd3cdfa7556df15202c5' ? Object.freeze(predecessor) : model.ref;
  policyRefs.set(model, ref); return ref;
}
